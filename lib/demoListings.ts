export const DEMO_LISTINGS_BY_ID = Object.fromEntries(
  DEMO_LISTINGS.map((listing) => [listing.id, listing])
) as Record<string, Listing>;

export function isDemoListing(listing: Listing): boolean {
  return listing.isDemo === true || listing.isPresentationDemo === true;
}

/** Keep the current ranking/sort within each group while always showing real items first. */
export function prioritizeRealListings(listings: Listing[]): Listing[] {
  return [
    ...listings.filter((listing) => !isDemoListing(listing)),
    ...listings.filter(isDemoListing),
  ];
}
